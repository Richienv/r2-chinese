import { t } from './i18n.ts'

/** One numbered blank inside a printed textbook sentence. */
export interface ExamBlank {
  n: number
  answer: string
}

export interface FillPart {
  kind: 'blanks'
  id: string
  lesson: number
  title: string
  zh: string
  bank: string[]
  /** `{{n}}` marks blank n. */
  lines: string[]
  blanks: ExamBlank[]
}

export interface ChoicePart {
  kind: 'choice'
  id: string
  lesson: number
  title: string
  material: string
  options: string[]
  answer: string
  why: string
}

export type ExamPart = FillPart | ChoicePart

function fill(
  id: string,
  lesson: number,
  zh: string,
  bank: string[],
  lines: string[],
  answers: string[],
): FillPart {
  return {
    kind: 'blanks',
    id,
    lesson,
    title: t('Fill in the blanks'),
    zh,
    bank,
    lines,
    blanks: answers.map((answer, index) => ({ n: index + 1, answer })),
  }
}

function choice(id: string, lesson: number, material: string, options: string[], answer: string, why: string): ChoicePart {
  return { kind: 'choice', id, lesson, title: t('Single choice'), material, options, answer, why }
}

